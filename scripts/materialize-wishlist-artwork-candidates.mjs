import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const CANDIDATE_MODULE = path.join(ROOT, "src", "data", "wishlist-artwork-candidates.ts");
const CANDIDATE_FILES_MODULE = path.join(ROOT, "src", "data", "wishlist-artwork-candidate-files.ts");
const OUTPUT_DIR = path.join(ROOT, "public", "covers", "wishlist-candidates");
const MAX_IMAGE_BYTES = 3 * 1024 * 1024;
const CONCURRENCY = 8;
const MODULE_PREFIX = "export const WISHLIST_ARTWORK_CANDIDATES: WishlistArtworkCandidate[] = ";
const CHECK_ONLY = process.argv.includes("--check");

function imageType(bytes) {
  if (bytes.length > 24 && bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) return "png";
  if (bytes.length > 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) return "jpg";
  return "";
}

function validId(value) {
  return /^[a-z0-9][a-z0-9-]*$/i.test(String(value ?? ""));
}

async function loadCandidates() {
  const source = await fs.readFile(CANDIDATE_MODULE, "utf8");
  const start = source.indexOf(MODULE_PREFIX);
  if (start < 0) throw new Error("Wishlist artwork candidate registry marker not found.");
  const jsonStart = start + MODULE_PREFIX.length;
  const end = source.indexOf(";\n", jsonStart);
  if (end < 0) throw new Error("Wishlist artwork candidate registry terminator not found.");
  const candidates = JSON.parse(source.slice(jsonStart, end));
  if (!Array.isArray(candidates)) throw new Error("Wishlist artwork candidate registry must be an array.");
  return candidates;
}

async function fetchOnce(url) {
  const response = await fetch(url, {
    headers: { "User-Agent": "RetroCollection-WishlistArtworkMaterializer/1.0" },
    signal: AbortSignal.timeout(30000),
  });
  if (!response.ok) throw new Error("HTTP " + response.status);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (!bytes.length || bytes.length > MAX_IMAGE_BYTES) throw new Error("invalid image size");
  return bytes;
}

function libretroAliasUrl(candidate, bytes) {
  if (candidate.source !== "libretro-thumbnails" || imageType(bytes)) return "";
  const alias = bytes.toString("utf8").trim();
  if (!/^[^/\\\r\n]+\.(png|jpe?g)$/i.test(alias) || alias.includes("..")) return "";
  const base = candidate.sourceUrl.slice(0, candidate.sourceUrl.lastIndexOf("/") + 1);
  return new URL(alias, base).toString();
}

async function fetchBytes(candidate) {
  let lastError = null;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      let bytes = await fetchOnce(candidate.sourceUrl);
      const aliasUrl = libretroAliasUrl(candidate, bytes);
      if (aliasUrl) bytes = await fetchOnce(aliasUrl);
      return bytes;
    } catch (error) {
      lastError = error;
      if (attempt < 3) await new Promise((resolve) => setTimeout(resolve, attempt * 700));
    }
  }
  throw new Error("Could not materialize " + candidate.id + ": " + String(lastError));
}

async function existingCandidateState(candidate) {
  if (!validId(candidate.id)) throw new Error("Invalid candidate id: " + candidate.id);
  for (const extension of ["png", "jpg"]) {
    const destination = path.join(OUTPUT_DIR, candidate.id + "." + extension);
    try {
      const bytes = await fs.readFile(destination);
      if (bytes.length <= MAX_IMAGE_BYTES && imageType(bytes) === extension) {
        return { destination, extension, valid: true };
      }
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  return { destination: "", extension: "", valid: false };
}

async function materialize(candidate) {
  const existing = await existingCandidateState(candidate);
  if (existing.valid) return { downloaded: false };

  const bytes = await fetchBytes(candidate);
  const actualType = imageType(bytes);
  if (!actualType) throw new Error("Candidate " + candidate.id + " returned unsupported image bytes.");

  const destination = path.join(OUTPUT_DIR, candidate.id + "." + actualType);
  await fs.writeFile(destination, bytes);
  for (const extension of ["png", "jpg"]) {
    if (extension !== actualType) {
      await fs.rm(path.join(OUTPUT_DIR, candidate.id + "." + extension), { force: true });
    }
  }
  return { downloaded: true };
}

function renderCandidateFilesModule(mapping) {
  return `// Generated by scripts/materialize-wishlist-artwork-candidates.mjs. Do not edit by hand.
export const WISHLIST_ARTWORK_CANDIDATE_FILES: Record<string, string> = ${JSON.stringify(mapping, null, 2)};
`;
}

async function buildLocalFileMap(candidates) {
  const mapping = {};
  const invalid = [];
  for (const candidate of candidates) {
    const state = await existingCandidateState(candidate);
    if (!state.valid) {
      invalid.push(candidate.id);
      continue;
    }
    mapping[candidate.id] = "/covers/wishlist-candidates/" + candidate.id + "." + state.extension;
  }
  return { mapping, invalid };
}

const candidates = await loadCandidates();

if (CHECK_ONLY) {
  const { mapping, invalid } = await buildLocalFileMap(candidates);
  if (invalid.length) {
    const suffix = invalid.length > 12 ? " (+" + (invalid.length - 12) + " more)" : "";
    throw new Error("Missing or invalid materialized Wishlist artwork: " + invalid.slice(0, 12).join(", ") + suffix);
  }
  const expectedModule = renderCandidateFilesModule(mapping);
  const currentModule = await fs.readFile(CANDIDATE_FILES_MODULE, "utf8").catch(() => "");
  if (currentModule !== expectedModule) throw new Error("Wishlist candidate file map is stale. Re-run materialization.");
  console.log(JSON.stringify({ candidates: candidates.length, valid: candidates.length, runtimeDirectory: "/covers/wishlist-candidates" }, null, 2));
  process.exit(0);
}

await fs.mkdir(OUTPUT_DIR, { recursive: true });

let cursor = 0;
let downloaded = 0;
async function worker() {
  while (cursor < candidates.length) {
    const index = cursor;
    cursor += 1;
    const result = await materialize(candidates[index]);
    if (result.downloaded) downloaded += 1;
  }
}
await Promise.all(Array.from({ length: Math.min(CONCURRENCY, Math.max(candidates.length, 1)) }, () => worker()));

const { mapping, invalid } = await buildLocalFileMap(candidates);
if (invalid.length) throw new Error("Materialization incomplete: " + invalid.join(", "));
await fs.writeFile(CANDIDATE_FILES_MODULE, renderCandidateFilesModule(mapping));

const expectedFiles = new Set(Object.values(mapping).map((url) => path.basename(url)));
for (const name of await fs.readdir(OUTPUT_DIR)) {
  if (!expectedFiles.has(name)) await fs.rm(path.join(OUTPUT_DIR, name), { force: true });
}

console.log(JSON.stringify({
  candidates: candidates.length,
  downloaded,
  reused: candidates.length - downloaded,
  runtimeDirectory: "/covers/wishlist-candidates",
}, null, 2));
